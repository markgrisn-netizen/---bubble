import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { selectSiteAdapter } from './adapters.ts';
import { classifyHttpFailure, SessionHttpClient, validatePublicChapterUrl } from './httpSession.ts';

test('selectSiteAdapter automatically chooses official APIs and site-specific adapters', () => {
  const md = selectSiteAdapter(
    new URL('https://mangadex.org/chapter/aa1285ad-6f64-4e66-877d-204544e37a83')
  );
  assert.equal(md.id, 'mangadex_api');

  const wt = selectSiteAdapter(
    new URL('https://www.webtoons.com/en/fantasy/tower-of-god/season-1-ep-0/viewer?title_no=95&episode_no=1')
  );
  assert.equal(wt.id, 'webtoons_viewer');

  const cubari = selectSiteAdapter(new URL('https://cubari.moe/read/gist/sample/1/1/'));
  assert.equal(cubari.id, 'cubari_api');

  const generic = selectSiteAdapter(new URL('https://example-reader.org/manga/ch-10'));
  assert.equal(generic.id, 'smart_html_js');
});

test('classifyHttpFailure accurately distinguishes WAF/Captcha, Auth, Hotlink 403, Rate Limit, and IP blocks', () => {
  const waf = classifyHttpFailure(
    403,
    { server: 'cloudflare', 'cf-mitigated': 'challenge' },
    '<html><title>Just a moment...</title><div class="cf-turnstile"></div></html>',
    'page'
  );
  assert.equal(waf.category, 'WAF_OR_CAPTCHA');

  const auth = classifyHttpFailure(
    401,
    { 'www-authenticate': 'Bearer realm="members"' },
    'Login required',
    'page'
  );
  assert.equal(auth.category, 'AUTH_REQUIRED');

  const hotlink = classifyHttpFailure(
    403,
    { server: 'nginx' },
    'Access Denied',
    'cdn_image'
  );
  assert.equal(hotlink.category, 'HOTLINK_REFERER_BLOCK');

  const rateLimit = classifyHttpFailure(
    429,
    { 'retry-after': '45' },
    'Too Many Requests',
    'page'
  );
  assert.equal(rateLimit.category, 'RATE_LIMITED');
  assert.ok(rateLimit.explanation.includes('45s'));

  const cfBlock = classifyHttpFailure(
    403,
    { server: 'CloudFront', 'x-cache': 'Error from cloudfront' },
    'Generated by cloudfront',
    'page'
  );
  assert.equal(cfBlock.category, 'IP_OR_GEO_BLOCK');
});

test('validatePublicChapterUrl blocks SSRF targets and unsafe protocols', () => {
  assert.throws(() => validatePublicChapterUrl('http://127.0.0.1:3000/api/projects'));
  assert.throws(() => validatePublicChapterUrl('http://169.254.169.254/latest/meta-data/'));
  assert.throws(() => validatePublicChapterUrl('file:///etc/passwd'));
  const ok = validatePublicChapterUrl('https://www.webtoons.com/en/fantasy/test/viewer?title_no=1&episode_no=1');
  assert.equal(ok.hostname, 'www.webtoons.com');
});

test('SessionHttpClient tracks redirects, persists Set-Cookie jar, and enforces Referer on CDN images', async () => {
  const pngBytes = Buffer.from(
    'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==',
    'base64'
  );

  const server = http.createServer((req, res) => {
    if (req.url === '/start') {
      res.statusCode = 302;
      res.setHeader('Location', '/viewer');
      res.setHeader('Set-Cookie', 'reader_sess=valid_tok_99; Path=/; HttpOnly');
      res.end();
      return;
    }

    if (req.url === '/viewer') {
      res.statusCode = 200;
      res.setHeader('Content-Type', 'text/html; charset=utf-8');
      res.end('<html><title>Test Chapter</title><body><img src="/cdn/page1.png" /></body></html>');
      return;
    }

    if (req.url === '/cdn/page1.png') {
      const hasReferer = (req.headers.referer || '').includes('/viewer');
      const hasCookie = (req.headers.cookie || '').includes('reader_sess=valid_tok_99');
      if (!hasReferer || !hasCookie) {
        res.statusCode = 403;
        res.setHeader('Content-Type', 'text/plain');
        res.end('403 Hotlink / Session Denied');
        return;
      }
      res.statusCode = 200;
      res.setHeader('Content-Type', 'image/png');
      res.end(pngBytes);
      return;
    }

    res.statusCode = 404;
    res.end('Not found');
  });

  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', () => resolve()));
  const addr = server.address();
  assert.ok(addr && typeof addr === 'object');
  const baseUrl = `http://127.0.0.1:${addr.port}`;

  try {
    const client = new SessionHttpClient(undefined, { allowPrivateHosts: true });
    const pageRes = await client.requestText(`${baseUrl}/start`);

    assert.equal(pageRes.status, 200);
    assert.equal(pageRes.redirectChain.length, 1);
    assert.equal(pageRes.redirectChain[0].status, 302);
    assert.equal(pageRes.cookiesCount, 1);

    // Without the viewer Referer, CDN returns 403
    const bareClient = new SessionHttpClient(undefined, { allowPrivateHosts: true });
    const denied = await bareClient.requestBinary(`${baseUrl}/cdn/page1.png`, {
      referer: 'https://other-site.invalid/',
    });
    assert.equal(denied.status, 403);
    assert.equal(denied.ok, false);

    // With shared cookie jar + viewer Referer, CDN returns 200 PNG
    const allowed = await client.requestBinary(`${baseUrl}/cdn/page1.png`, {
      referer: pageRes.finalUrl,
    });
    assert.equal(allowed.status, 200);
    assert.equal(allowed.ok, true);
    assert.equal(allowed.contentType, 'image/png');
    assert.ok(allowed.buffer.equals(pngBytes));
  } finally {
    await new Promise<void>((resolve) => server.close(() => resolve()));
  }
});
